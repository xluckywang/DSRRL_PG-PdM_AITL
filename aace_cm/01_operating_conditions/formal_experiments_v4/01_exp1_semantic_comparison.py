def _apply_expert_temperature_rules(
    y_pred: np.ndarray, energy_proxy: np.ndarray, temp_proxy: np.ndarray
) -> np.ndarray:
    """STOPPED 能量阈值修正 + 启动类型温度上下文修正。"""
    y = y_pred.copy()
    STOPPED_ENERGY_TH = 0.52
    y[energy_proxy < STOPPED_ENERGY_TH] = 0
    if len(temp_proxy) > 0:
        temp_threshold = np.percentile(temp_proxy, 75)
        for i in range(1, len(y)):
            if y[i] in (1, 2, 3) and y[i - 1] == 0:
                y[i] = 3 if temp_proxy[i] > temp_threshold else 1
    return y


def _apply_physical_expert_rules(
    y_pred: np.ndarray, energy_proxy: np.ndarray, temp_proxy: np.ndarray,
    running_std: float, trend_window: int = 60
) -> Tuple[np.ndarray, np.ndarray]:
    """物理专家规则注入（SHUTDOWN / LOAD_CHANGE / 启动类型修正）。

    COLD_START 检测逻辑修正（物理原则）：
    - 传感器仅在机器运行时记录，因此"中间 STOPPED"通常是测量间隙或负荷骤降，
      而非真实关机。
    - 真正的冷启动（COLD_START）必须满足：
        1. STOPPED 持续足够长（≥冷启动最短停机时长），说明机器有充足时间冷却；
        2. 重新启动时的 temp_proxy 较低，说明机器仍处于冷态。
    - 否则（STOPPED 持续很短，或停机后仍热），均归为 HOT_START。
    - 若无法判断，统一归为 HOT_START（保守处理，避免虚标稀有状态）。
    """
    y = y_pred.copy()
    n = len(y)
    expert_mask = np.zeros(n, dtype=bool)

    SHUTDOWN_WINDOW = 5
    for i in range(n - 1):
        if y[i + 1] == 0 and y[i] != 0:
            for k in range(max(0, i - SHUTDOWN_WINDOW + 1), i + 1):
                y[k] = 4
                expert_mask[k] = True

    for i in range(1, n):
        if y[i] not in (2, 5):
            continue
        if abs(energy_proxy[i] - energy_proxy[i - 1]) > running_std * 2.0:
            y[i] = 5
            expert_mask[i] = True

    # ── 启动类型修正 ───────────────────────────────────────────────────────────
    # 关键洞察：
    # - STOPPED 段之前的状态决定了它是"真关机后的重启"还是"运行中短暂间隙"
    # - 如果 STOPPED 段之前有大段连续 RUNNING（NORMAL/HOT），说明是短暂间隙 → HOT_START
    # - 如果 STOPPED 段之前 RUNNING 长度较短，说明可能是关机冷却后重启 → COLD_START
    #   （需同时满足：停机前 RUNNING 长度 < 阈值，说明之前状态可能不热了）
    # - 简单向前扫描（不依赖能量阈值），物理直觉：停机前设备不够热 → 冷启动
    COLD_START_PRE_RUNNING_SAMPLES = 300
    temp_threshold = np.percentile(temp_proxy, 75) if len(temp_proxy) > 0 else np.inf

    i = 1
    while i < n:
        # 触发条件：当前是RUNNING(1/2/3)，前一个点是STOPPED(0)
        if not (y[i - 1] == 0 and y[i] in (1, 2, 3)):
            i += 1
            continue

        # 向前扫描 STOPPED 段之前的连续 RUNNING 长度
        # 如果前面 RUNNING 很长，说明设备一直在热态运行，短暂 STOPPED 是生产间隙 → HOT
        # 如果前面 RUNNING 很短或不连贯，说明设备可能刚从冷态启动 → COLD
        pre_len = 0
        for j in range(i - 2, max(0, i - 2 - COLD_START_PRE_RUNNING_SAMPLES) - 1, -1):
            if y[j] in (1, 2, 3):
                pre_len += 1
            else:
                break

        is_cold = pre_len < COLD_START_PRE_RUNNING_SAMPLES and temp_proxy[i] < temp_threshold
        if is_cold:
            y[i] = 1
        else:
            y[i] = 3
        expert_mask[i] = True
        i += 1
        continue

    return y, expert_mask


def _viterbi_smoothing(y_seq: np.ndarray) -> np.ndarray:
    """HMM Viterbi 时序平滑。"""
    n_states = 6
    T = np.full((n_states, n_states), -np.inf)
    T_PENALTY, T_VALID, T_SELF = -20.0, -2.0, 0.0
    T[0, 0] = -0.5     # STOPPED 自环降低权重
    T[0, 1] = T_VALID; T[0, 2] = T_PENALTY; T[0, 3] = T_VALID
    T[0, 4] = T_PENALTY; T[0, 5] = T_PENALTY
    T[1, 0] = T_PENALTY; T[1, 1] = T_SELF; T[1, 2] = T_VALID; T[1, 3] = T_PENALTY
    T[1, 4] = T_VALID; T[1, 5] = T_PENALTY
    T[2, 0] = T_PENALTY; T[2, 1] = T_PENALTY; T[2, 2] = T_SELF; T[2, 3] = T_PENALTY
    T[2, 4] = T_VALID; T[2, 5] = T_VALID
    T[3, 0] = T_PENALTY; T[3, 1] = T_PENALTY; T[3, 2] = T_VALID; T[3, 3] = T_SELF
    T[3, 4] = T_VALID; T[3, 5] = T_PENALTY
    T[4, 0] = T_VALID; T[4, 1] = T_PENALTY; T[4, 2] = T_PENALTY; T[4, 3] = T_PENALTY
    T[4, 4] = T_SELF; T[4, 5] = T_PENALTY
    T[5, 0] = T_PENALTY; T[5, 1] = T_PENALTY; T[5, 2] = T_VALID; T[5, 3] = T_PENALTY
    T[5, 4] = T_VALID; T[5, 5] = T_SELF

    seq_len = len(y_seq)
    dp = np.full((seq_len, n_states), -np.inf)
    pointers = np.zeros((seq_len, n_states), dtype=int)
    dp[0, y_seq[0]] = 0.0
    for c in range(n_states):
        if c != y_seq[0]:
            dp[0, c] = -5.0
    for i in range(1, seq_len):
        obs = y_seq[i]
        emission = np.full(n_states, -5.0)
        emission[obs] = 0.0
        for cs in range(n_states):
            for ps in range(n_states):
                s = dp[i - 1, ps] + T[ps, cs] + emission[cs]
                if s > dp[i, cs]:
                    dp[i, cs] = s
                    pointers[i, cs] = ps
    path = np.zeros(seq_len, dtype=int)
    path[-1] = np.argmax(dp[-1])
    for i in range(seq_len - 1, 0, -1):
        path[i - 1] = pointers[i, path[i]]
    return path


