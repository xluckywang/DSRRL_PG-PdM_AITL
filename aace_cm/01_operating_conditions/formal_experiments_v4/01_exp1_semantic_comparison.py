def _list_common_dates(device: str, date_mode: str = "exp0_recommended") -> List[str]:
    feature_dir = PATHS.vw_features_dir / device
    label_dir = PATHS.vw_labels_dir / device
    feature_dates = {p.name.replace("_features.csv", "") for p in feature_dir.glob("*_features.csv")}
    label_dates = {p.name.replace("_labels.csv", "") for p in label_dir.glob("*_labels.csv")}
    common_dates = feature_dates & label_dates

    if date_mode == "exp0_recommended":
        return [d for d in get_exp0_recommended_dates() if d in common_dates]
    if date_mode == "all_labels":
        return sorted(common_dates)
    raise ValueError(f"Unknown date_mode: {date_mode}")


def _load_days(device: str, dates: List[str]) -> List[DayData]:
    """加载指定日期列表的原始特征和 Physics-Informed 伪标签。"""
    out: List[DayData] = []
    for date in dates:
        feat_file = PATHS.vw_features_dir / device / f"{date}_features.csv"
        lab_file = PATHS.vw_labels_dir / device / f"{date}_labels.csv"
        if not feat_file.exists() or not lab_file.exists():
            continue
        df_feat = pd.read_csv(feat_file)
        df_lab = pd.read_csv(lab_file)
        lc = "state"
        ml = min(len(df_feat), len(df_lab))
        y_new = df_lab[lc].iloc[:ml].astype(int).to_numpy()
        df_feat = df_feat.iloc[:ml].reset_index(drop=True)
        out.append(DayData(date=date, df_feature=df_feat, y_new=y_new))
    return out


