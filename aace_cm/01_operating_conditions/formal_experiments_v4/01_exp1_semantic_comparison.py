def _eval(y_true: np.ndarray, y_pred: np.ndarray) -> Dict:
    """返回完整评估指标字典。"""
    states = list(range(6))
    macro_f1 = f1_score(y_true, y_pred, average="macro", zero_division=0)
    acc = accuracy_score(y_true, y_pred)
    per_state_f1 = {}
    for s in states:
        per_state_f1[STATE_NAMES[s]] = f1_score(
            (y_true == s).astype(int), (y_pred == s).astype(int), zero_division=0
        )
    return {"macro_f1": macro_f1, "accuracy": acc, "per_state_f1": per_state_f1}


