def _variant_expert_only(x: np.ndarray, energy_proxy: np.ndarray,
                         temp_proxy: np.ndarray) -> np.ndarray:
    """A1: 纯专家规则（无 ML / 无 Viterbi）——只用物理阈值和状态机。"""
    n = len(x)
    y = np.full(n, 2, dtype=int)   # 默认 NORMAL
    y[energy_proxy < 0.52] = 0     # 能量阈值标 STOPPED

    # SHUTDOWN
    for i in range(n - 1):
        if y[i + 1] == 0 and y[i] != 0:
            for k in range(max(0, i - 4), i + 1):
                y[k] = 4

    # LOAD_CHANGE
    run_mask = energy_proxy >= 0.52
    std_val = np.std(energy_proxy[run_mask]) if run_mask.sum() > 10 else 0.01
    for i in range(1, n):
        if y[i] not in (2, 5):
            continue
        if abs(energy_proxy[i] - energy_proxy[i - 1]) > std_val * 2.0:
            y[i] = 5

    # ── 启动类型修正（向前扫描逻辑）────────────────────────────
    # 与 _apply_physical_expert_rules 保持一致
    COLD_START_PRE_RUNNING_SAMPLES = 300
    temp_threshold = np.percentile(temp_proxy, 75) if len(temp_proxy) > 0 else np.inf

    i = 1
    while i < n:
        if not (y[i - 1] == 0 and y[i] in (1, 2, 3)):
            i += 1
            continue

        pre_len = 0
        for j in range(i - 2, max(0, i - 2 - COLD_START_PRE_RUNNING_SAMPLES) - 1, -1):
            if y[j] in (1, 2, 3):
                pre_len += 1
            else:
                break

        is_cold = pre_len < COLD_START_PRE_RUNNING_SAMPLES and temp_proxy[i] < temp_threshold
        if is_cold:
            y[i] = 1
        else:
            y[i] = 3
        i += 1
        continue

    return y


