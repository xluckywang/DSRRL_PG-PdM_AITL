def _cluster_to_label_mapping(y_train_all: np.ndarray, cluster_ids: np.ndarray,
                              n_clusters: int) -> Dict[int, int]:
    """聚类ID → 状态标签的映射（类频率逆加权投票）。

    问题：简单多数投票会被大类别（NORMAL/STOPPED）淹没稀有状态。
    方法：对每个聚类，用类频率的倒数作为权重，
         让稀有状态在投票时获得更高加权。
         最终映射选择加权得分最高的类别。

    数学：score[class] = Σ(weight[i] for i in cluster_points)
          其中 weight[class] = 1 / (frequency_of_class + smoothing)
    """
    # 计算各类别在训练集中的频率（用于加权）
    all_labels, all_counts = np.unique(y_train_all, return_counts=True)
    total = len(y_train_all)
    class_freq = {int(lbl): cnt / total for lbl, cnt in zip(all_labels, all_counts)}

    # 平滑系数，避免稀有类权重爆炸
    smoothing = 0.001
    class_weight = {lbl: 1.0 / (freq + smoothing) for lbl, freq in class_freq.items()}

    mapping: Dict[int, int] = {}
    for cid in range(n_clusters):
        idx = np.where(cluster_ids == cid)[0]
        if len(idx) == 0:
            mapping[cid] = 2
            continue
        labels_in_cluster = y_train_all[idx]
        # 计算各类别的加权得分
        weighted_scores: Dict[int, float] = {}
        for lbl, weight in class_weight.items():
            count_in_cluster = int(np.sum(labels_in_cluster == lbl))
            weighted_scores[lbl] = count_in_cluster * weight
        # 选加权得分最高的类别
        mapping[cid] = int(max(weighted_scores, key=weighted_scores.get))
    return mapping


