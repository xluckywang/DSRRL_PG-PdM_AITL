def run_exp1(fast: bool = False, date_mode: str = "exp0_recommended") -> None:
    PATHS.ensure_dirs()
    device = COMMON.device
    feature_cols = list(EXP1.feature_cols)

    all_dates = _list_common_dates(device, date_mode=date_mode)
    if not all_dates:
        raise RuntimeError(f"Label files not found for device: {PATHS.vw_labels_dir / device}")

    test_dates = all_dates[:NUM_TEST_DAYS]
    train_dates = all_dates[NUM_TEST_DAYS:]

    if fast:
        train_dates = train_dates[: EXP1.fast_num_days]
        test_dates = test_dates[: 2]
        print(f"[Exp1] Fast mode: train={len(train_dates)} days, test={len(test_dates)} days", flush=True)
    else:
        print(f"[Exp1] Ablation Study | device={device}", flush=True)
        print(f"[Exp1] Date mode: {date_mode} ({len(all_dates)} days)", flush=True)
        print(f"[Exp1] Train: {train_dates[0]} ~ {train_dates[-1]} ({len(train_dates)} days)", flush=True)
        print(f"[Exp1] Test:  {test_dates[0]} ~ {test_dates[-1]} ({len(test_dates)} days)", flush=True)

    train_days = _load_days(device, train_dates)
    test_days = _load_days(device, test_dates)

    if not train_days or not test_days:
        raise RuntimeError("Train or test set is empty")

    # 拼接训练数据（原始特征 + NEW 标签）
    x_train_list = [d.df_feature[feature_cols].to_numpy() for d in train_days]
    y_train_list = [d.y_new for d in train_days]
    x_train_all = np.vstack(x_train_list)
    y_train_all = np.concatenate(y_train_list)

    # 构造训练集物理特征
    _, _, _ = _build_physics_features(x_train_all)  # 仅触发导入
    pf_train_list = []
    for d, x in zip(train_days, x_train_list):
        pf, _, _ = _build_physics_features(x)
        pf_train_list.append(pf)
    x_train_phys = np.vstack(pf_train_list)

    # 测试集数据
    test_x_list = [d.df_feature[feature_cols].to_numpy() for d in test_days]
    test_y_list = [d.y_new for d in test_days]
    y_test_all = np.concatenate(test_y_list)

    pf_test_list = []
    for d, x in zip(test_days, test_x_list):
        pf, en, tp = _build_physics_features(x)
        pf_test_list.append((pf, en, tp, x))
    x_test_phys = np.vstack([p[0] for p in pf_test_list])

    rows_detail: List[dict] = []
    all_preds: Dict[str, List[np.ndarray]] = {vid: [] for vid, _ in ABLATION_VARIANTS}

    for seed in COMMON.seeds:
        total_variants = len(ABLATION_VARIANTS)
        total_days = len(pf_test_list)

        # ── StandardScaler（所有物理特征统一归一化）─────────────────────────
        scaler = StandardScaler()
        scaler.fit(x_train_phys)

        # ── 只取 NORMAL 状态样本训练 AE ────────────────────────────────────
        normal_mask = (y_train_all == NORMAL_STATE_ID)
        x_normal = x_train_phys[normal_mask].copy()
        x_normal_scaled = scaler.transform(x_normal)

        # AE 下采样（避免训练过慢；NORMAL 样本通常很多）
        MAX_NORMAL = 50_000
        if len(x_normal_scaled) > MAX_NORMAL:
            rng = np.random.default_rng(seed)
            idx = rng.choice(len(x_normal_scaled), MAX_NORMAL, replace=False)
            x_normal_scaled = x_normal_scaled[idx]

        # ── 每个 seed 独立训练 AE（无监督，随机初始化）─────────────────────
        ae_struct = "SimpleAE"
        ae_epochs = 100
        ae_model = _train_ae(x_normal_scaled, ae_struct, ae_epochs, seed)

        # ── 计算训练集的 AE 聚类特征 ────────────────────────────────────────
        #   聚类特征 = per-dim 重构误差 + latent 向量
        #   这比原始物理特征对状态更敏感，且方差更小
        x_train_scaled = scaler.transform(x_train_phys)
        train_ae_feats = _ae_clustering_features(ae_model, x_train_scaled)

        # ── 计算训练数据的 AE 特征（供 KNN 使用）────────────────────────────
        ae_feats_train = train_ae_feats

        rf_model = RandomForestClassifier(n_estimators=50, max_depth=10, random_state=seed)
        rf_model.fit(x_train_phys, y_train_all)

        for vid_idx, (vid, vname) in enumerate(ABLATION_VARIANTS):
            print(f"[Exp1] seed={seed} [{vid_idx+1}/{total_variants}] {vid} ...", flush=True)

            preds_day: List[np.ndarray] = []

            for day_idx, ((pf, energy, temp, x_raw), y_day) in enumerate(
                zip(pf_test_list, test_y_list)
            ):
                if vid == "A1_ExpertOnly":
                    y_pred = _variant_expert_only(x_raw, energy, temp)
                elif vid == "A2_Expert+Viterbi":
                    y_pred = _variant_expert_viterbi(x_raw, energy, temp)
                elif vid == "A3_AE+KNN-only":
                    y_pred = _variant_ae_only(pf, scaler, ae_model, ae_feats_train, y_train_all)
                elif vid == "A4_AE+KNN+Rule":
                    y_pred, _ = _variant_ae_rule(
                        pf, energy, temp, scaler, ae_model, ae_feats_train, y_train_all)
                elif vid == "A5_AE+KNN+All":
                    y_pred = _variant_ae_all(
                        pf, energy, temp, scaler, ae_model, ae_feats_train, y_train_all, y_train_all)
                elif vid == "A6_RF-only":
                    y_pred = rf_model.predict(pf)
                elif vid == "A7_RF+Rule":
                    y_pred = _rf_wrapper_rule(rf_model, x_raw, pf, energy, temp)
                else:  # A8
                    y_pred = _rf_wrapper_all(rf_model, x_raw, pf, energy, temp)

                preds_day.append(y_pred)

            y_pred_all = np.concatenate(preds_day)
            metrics = _eval(y_test_all, y_pred_all)
            rows_detail.append({
                "seed": seed, "variant": vid, "variant_name": vname,
                "macro_f1": metrics["macro_f1"],
                "accuracy": metrics["accuracy"],
            })
            for sname, f1 in metrics["per_state_f1"].items():
                rows_detail[-1][f"f1_{sname}"] = f1

            all_preds[vid].append(y_pred_all)

    df_detail = pd.DataFrame(rows_detail)

    # 汇总统计
    summary_cols = ["variant", "variant_name", "macro_f1", "accuracy"] + [
        f"f1_{STATE_NAMES[s]}" for s in range(6)
    ]
    available = [c for c in summary_cols if c in df_detail.columns]
    summary = (
        df_detail.groupby(["variant", "variant_name"], as_index=False)[
            [c for c in available if c not in ("variant", "variant_name")]
        ]
        .agg({c: ("mean", "std") for c in available if c not in ("variant", "variant_name")})
    )
    summary.columns = ["_".join(col).strip("_") for col in summary.columns.values]
    summary = summary.rename(columns={
        "variant_": "variant", "variant_name_": "variant_name",
        "macro_f1_mean": "macro_f1_mean", "macro_f1_std": "macro_f1_std",
        "accuracy_mean": "accuracy_mean", "accuracy_std": "accuracy_std",
    })

    # per-state F1 均值
    for s in range(6):
        c_mean = f"f1_{STATE_NAMES[s]}_mean"
        c_std = f"f1_{STATE_NAMES[s]}_std"
        if c_mean in summary.columns:
            summary = summary.rename(columns={c_mean: f"f1_{STATE_NAMES[s]}_mean"})
            summary = summary.rename(columns={c_std: f"f1_{STATE_NAMES[s]}_std"})

    # 保存 CSV（outputs 目录）
    out_summary = PATHS.exp1_semantic_dir / "exp1_ablation_summary.csv"
    out_detail = PATHS.exp1_semantic_dir / "exp1_ablation_per_seed.csv"
    summary.to_csv(out_summary, index=False, float_format="%.6f")
    df_detail.to_csv(out_detail, index=False, float_format="%.6f")
    print(f"[Exp1] CSV -> {out_summary}")
    print(f"[Exp1] CSV -> {out_detail}")

    # 同时保存到 figures/ 目录（供独立绘图 notebook 使用）
    PATHS.figures_dir.mkdir(parents=True, exist_ok=True)
    fig_summary = PATHS.figures_dir / "exp1_ablation_summary.csv"
    fig_detail = PATHS.figures_dir / "exp1_ablation_per_seed.csv"
    summary.to_csv(fig_summary, index=False, float_format="%.6f")
    df_detail.to_csv(fig_detail, index=False, float_format="%.6f")
    print(f"[Exp1] CSV -> {fig_summary}")
    print(f"[Exp1] CSV -> {fig_detail}")

    # 绘图（同时保存到 figures/ 目录）
    _plot_ablation_bar(summary)
    shutil.copy(
        PATHS.exp1_figures_dir / "exp1_ablation_bar.png",
        PATHS.figures_dir / "exp1_ablation_bar.png",
    )

    # 混淆矩阵（用第一个 seed 的 A5 结果）
    first_seed_idx = 0
    y_pred_final = all_preds["A5_AE+KNN+All"][first_seed_idx]
    _plot_confusion_matrix(y_test_all, y_pred_final)
    shutil.copy(
        PATHS.exp1_figures_dir / "exp1_confusion_matrix.png",
        PATHS.figures_dir / "exp1_confusion_matrix.png",
    )
    # 导出混淆矩阵数据为 CSV（供 figures.ipynb 绘图）
    cm_df = pd.DataFrame({
        "y_true": y_test_all,
        "y_pred": y_pred_final,
    })
    cm_csv = PATHS.figures_dir / "exp1_confusion_data.csv"
    cm_df.to_csv(cm_csv, index=False)
    print(f"[Exp1] CSV -> {cm_csv}")

    # 单天时序图（随机选 3 天）
    rng = random.Random(EXP1.figure_random_seed)
    n_plot = min(3, len(test_days))
    selected = rng.sample(test_days, n_plot) if len(test_days) > n_plot else test_days

    short_names = {vid: vname for vid, vname in ABLATION_VARIANTS}

    # 预计算每天在 all_preds 中的起止索引
    day_starts = [0] + list(np.cumsum([len(t) for t in test_y_list]))

    # 导出每天的时序数据为 CSV（供 figures.ipynb 绘图）
    # 格式：date, frame_idx, vib_x, vib_y, vib_z, y_true, pred_{variant}
    for d in selected:
        day_idx = test_days.index(d)
        s, e = day_starts[day_idx], day_starts[day_idx + 1]
        day_x = test_x_list[day_idx]
        day_y_true = test_y_list[day_idx]
        day_df = pd.DataFrame({
            "frame_idx": np.arange(len(day_x)),
            "vib_x": day_x[:, 0],
            "vib_y": day_x[:, 1],
            "vib_z": day_x[:, 2],
            "y_true": day_y_true,
        })
        for vid, _ in ABLATION_VARIANTS:
            day_df[f"pred_{vid}"] = all_preds[vid][first_seed_idx][s:e]
        day_csv = PATHS.figures_dir / f"exp1_day_comparison_{d.date}.csv"
        day_df.to_csv(day_csv, index=False, float_format="%.6f")
        print(f"[Exp1] CSV -> {day_csv}")

    for d in selected:
        day_idx = test_days.index(d)
        s, e = day_starts[day_idx], day_starts[day_idx + 1]
        day_x = test_x_list[day_idx]
        preds_for_day = {
            vid: all_preds[vid][first_seed_idx][s:e]
            for vid, _ in ABLATION_VARIANTS
        }
        _plot_day_comparison(d.date, day_x, test_y_list[day_idx], preds_for_day, short_names)
        shutil.copy(
            PATHS.exp1_figures_dir / f"exp1_day_comparison_{d.date}.png",
            PATHS.figures_dir / f"exp1_day_comparison_{d.date}.png",
        )

    print("[Exp1] Done", flush=True)
    print(f"[Exp1] figures_dir: {PATHS.figures_dir}")
    print(f"[Exp1] outputs_dir:  {PATHS.exp1_figures_dir}")


