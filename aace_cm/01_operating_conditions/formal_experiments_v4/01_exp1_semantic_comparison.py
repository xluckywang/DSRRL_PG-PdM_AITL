class FlexibleAutoEncoder(nn.Module):
    """Autoencoder trained on NORMAL data; recon-error profile discriminates states."""

    def __init__(self, input_dim: int, encoder_dims: List[int], decoder_dims: List[int]):
        super().__init__()
        enc: List[nn.Module] = []
        prev = input_dim
        for d in encoder_dims:
            enc += [nn.Linear(prev, d), nn.ReLU()]
            prev = d
        self.encoder = nn.Sequential(*enc)
        dec: List[nn.Module] = []
        for d in decoder_dims:
            dec += [nn.Linear(prev, d), nn.ReLU()]
            prev = d
        dec.append(nn.Linear(prev, input_dim))
        self.decoder = nn.Sequential(*dec)

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        return self.decoder(self.encoder(x))

    def encode(self, x: torch.Tensor) -> torch.Tensor:
        return self.encoder(x)


def _ae_structure(name: str) -> Tuple[List[int], List[int]]:
    if name == "SimpleAE":    return [8, 2], [8]
    if name == "FlexibleAE":   return [16, 8, 4], [8, 16]
    if name == "DeepAE":      return [32, 16, 8], [16, 32]
    return [8, 2], [8]   # fallback


def _train_ae(x_normal: np.ndarray, struct: str, epochs: int, seed: int,
              lr: float = 1e-3, wd: float = 1e-5, patience: int = 15) -> FlexibleAutoEncoder:
    """Train AE on NORMAL samples only; returns best model by val loss."""
    import random
    random.seed(seed); np.random.seed(seed); torch.manual_seed(seed)
    enc_d, dec_d = _ae_structure(struct)
    model = FlexibleAutoEncoder(x_normal.shape[1], enc_d, dec_d)
    model.to(_DEVICE)
    crit = nn.MSELoss()
    opt = torch.optim.Adam(model.parameters(), lr=lr, weight_decay=wd)
    tx = torch.tensor(x_normal, dtype=torch.float32)
    loader = torch.utils.data.DataLoader(tx, batch_size=512, shuffle=True, drop_last=True)
    best = float("inf"); best_st = None; pat = 0
    for ep in range(epochs):
        model.train()
        for xb in loader:
            opt.zero_grad(); loss = crit(model(xb), xb); loss.backward(); opt.step()
        with torch.no_grad():
            avg = float(crit(model(tx.to(_DEVICE)), tx.to(_DEVICE)))
        if avg < best * 0.9999:
            best, best_st, pat = avg, {k: v.cpu().clone() for k, v in model.state_dict().items()}, 0
        else:
            pat += 1
        if pat >= patience:
            break
    if best_st:
        model.load_state_dict(best_st)
    return model


@torch.no_grad()
def _recon_features(model: FlexibleAutoEncoder, x: np.ndarray) -> np.ndarray:
    """Recon-error feature vector (per-dim MSE + latent) for clustering."""
    tx = torch.tensor(x, dtype=torch.float32).to(_DEVICE)
    z = model.encode(tx).cpu().numpy()
    recon = model.decoder(torch.from_numpy(z)).cpu().numpy()
    # Per-dim squared reconstruction error
    per_dim_err = (recon - x) ** 2   # (N, D)
    # Also include latent representation
    return np.hstack([per_dim_err, z])   # (N, D + latent_dim)


