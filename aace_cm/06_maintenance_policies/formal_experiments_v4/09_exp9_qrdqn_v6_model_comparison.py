def plot_training_sensitivity(eval_records: pd.DataFrame, path: Path):
    rl = eval_records.copy()
    if rl.empty:
        return
    fig, axes = plt.subplots(1, 2, figsize=(13, 4.6))
    for method, g in rl.groupby("Method"):
        agg = g.groupby("Episode")["Avg. reward"].agg(["mean", "std"]).reset_index()
        x = agg["Episode"].to_numpy(dtype=float)
        y = agg["mean"].to_numpy(dtype=float)
        sd = agg["std"].fillna(0.0).to_numpy(dtype=float)
        axes[0].plot(x, y, marker="o", label=method)
        axes[0].fill_between(x, y - sd, y + sd, alpha=0.15)
        unmit = g.groupby("Episode")["Unmitigated rate"].agg(["mean", "std"]).reset_index()
        y2 = unmit["mean"].to_numpy(dtype=float)
        sd2 = unmit["std"].fillna(0.0).to_numpy(dtype=float)
        axes[1].plot(x, y2, marker="o", label=method)
        axes[1].fill_between(x, y2 - sd2, y2 + sd2, alpha=0.15)
    axes[0].set_title("Validation reward sensitivity")
    axes[0].set_xlabel("Training episodes")
    axes[0].set_ylabel("Avg. reward")
    axes[1].set_title("Unmitigated failure sensitivity")
    axes[1].set_xlabel("Training episodes")
    axes[1].set_ylabel("Unmitigated rate")
    for ax in axes:
        ax.grid(True, alpha=0.3)
        ax.legend(fontsize=8)
    fig.tight_layout()
    fig.savefig(path, dpi=300, bbox_inches="tight")
    plt.close(fig)


def plot_policy_example(env: MaintenanceEnv, policies: Dict[str, Callable[[np.ndarray], int]], path: Path):
    fig, axes = plt.subplots(len(policies) + 1, 1, figsize=(13, 2.45 * (len(policies) + 1)), sharex=True)
    risks = [env.base_risk[i] for i in range(env.n)]
    faults = env.fault_ratio
    axes[0].plot(risks, color="#333333", lw=1.4, label="health risk")
    axes[0].fill_between(np.arange(len(faults)), 0, np.maximum(faults, 0.02), color="#D55E00", alpha=0.25, label="fault window")
    axes[0].axhline(1.0, color="red", ls="--", lw=1)
    axes[0].legend(fontsize=8)
    axes[0].set_title(env.scenario.name)
    for ax, (name, policy) in zip(axes[1:], policies.items()):
        _, actions, hist = env.run_policy(policy)
        ax.plot([h["risk"] for h in hist], color="#555555", lw=1.0)
        for a, color in [(1, "#009E73"), (2, "#CC79A7"), (3, "#D55E00")]:
            idx = np.where(np.asarray(actions) == a)[0]
            if len(idx):
                ax.scatter(idx, [1.08 + 0.07 * a] * len(idx), s=14, color=color, label=ACTION_NAMES[a])
        ax.axhline(1.0, color="red", ls="--", lw=0.8)
        ax.set_ylim(0, max(1.8, float(np.max(risks)) * 1.15))
        ax.set_title(name)
        ax.grid(True, alpha=0.2)
        handles, labels = ax.get_legend_handles_labels()
        if handles:
            ax.legend(handles, labels, fontsize=8, loc="upper right")
    axes[-1].set_xlabel("Window step")
    fig.tight_layout()
    fig.savefig(path, dpi=300, bbox_inches="tight")
    plt.close(fig)


def choose_policy_example_env(test_envs: Sequence[MaintenanceEnv]) -> MaintenanceEnv:
    scored = []
    for env in test_envs:
        score = float(np.max(env.base_risk) + 0.7 * np.mean(env.fault_ratio > 0.25))
        scored.append((score, env))
    return sorted(scored, key=lambda x: x[0], reverse=True)[0][1]


