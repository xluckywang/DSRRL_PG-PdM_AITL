"""
AACE-CM-Exp9 v6: model-comparison benchmark for multi-action maintenance decisions.

This version keeps the v5 Exp7/Exp8 state pipeline, but changes the paper-facing
benchmark in three important ways:

Important implementation choices:
  1. Exp4/Exp7 risk is read from the Exp7 cached Dual-Space Health Index (DSHI)
     trajectory generated by the fixed Exp3/Exp4 VAE+DBSCAN representation.
     If a scenario is missing in the cache, the script falls back to the
     window-level RMS health-risk ratio and records that fallback in metadata.
  2. Exp7 future risk is represented by an online short-horizon forecast over
     the DSHI/risk trajectory, computed only from previous risk history.
  3. Exp8 fault probability is produced by a sklearn ExtraTrees classifier on
     time/frequency window features; test labels are never used in the state.
  4. Rewards are costs: operation benefit minus maintenance, downtime,
     risk-exposure, unnecessary-maintenance, and unresolved-failure costs.
  5. The default evaluation uses the full available decision timeline instead
     of cropped fault-neighborhood windows.
  6. The main intervention metric is event-level, with action cooldown, so it is
     not inflated by repeated maintenance choices in adjacent windows.
  7. The model table explicitly separates DQN, Double-DQN, Dueling-DQN,
     Double-Dueling-DQN, temporal DQN variants, QR-DQN, LSTM-QR-DQN,
     HiLSTM-Attn-QR-DQN, PPO, SAC, and a SCORER-inspired DQN baseline.
"""

