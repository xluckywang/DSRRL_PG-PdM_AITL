def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--fast", action="store_true", help="quick balanced subset")
    parser.add_argument("--force", action="store_true", help="reserved for compatibility")
    parser.add_argument("--seeds", default=None, help="comma separated seeds, default: 11,22,33 (or 11 in fast mode)")
    parser.add_argument("--episode-grid", default=None, help="comma separated episode checkpoints")
    parser.add_argument("--methods", default=None, help="comma separated model names; default runs the full model comparison")
    parser.add_argument("--output-suffix", default="", help="suffix appended to the default output directory")
    parser.add_argument("--out-dir", default=None, help="explicit output directory; relative paths are resolved under formal_experiments_v4")
    parser.add_argument(
        "--crop-fault-neighborhood",
        action="store_true",
        help="compatibility mode: evaluate cropped fault-neighborhood windows instead of the full timeline",
    )
    args = parser.parse_args()

    seeds = parse_int_list(args.seeds) if args.seeds else ([11] if args.fast else [11, 22, 33])
    if args.episode_grid:
        episode_grid = parse_int_list(args.episode_grid)
    else:
        episode_grid = [80, 160, 240] if args.fast else [100, 300, 500, 1000]
    methods = parse_str_list(args.methods) if args.methods else None
    run_exp9(
        fast=args.fast,
        seeds=seeds,
        episode_grid=episode_grid,
        methods=methods,
        crop_fault_neighborhood=args.crop_fault_neighborhood,
        force=args.force,
        output_suffix=args.output_suffix,
        out_dir_override=args.out_dir,
    )


if __name__ == "__main__":
    main()
