def _select_balanced_params(
    fast: bool,
    device: str = "BA1",
    pcts: Optional[Tuple[float, ...]] = None,
    severities: Optional[Tuple[int, ...]] = None,
) -> List[Tuple[str, Path, dict]]:
    rows = []
    for name, path, params in _params_iter(device):
        parsed = _parse_fault_params_from_name(name)
        fault_type = str(params.get("fault_type", parsed["fault_type"]))
        pct = round(float(params.get("percentage", parsed["percentage"])), 4)
        sev = int(params.get("severity_level", parsed["severity_level"]))
        if pcts is not None and pct not in {round(float(p), 4) for p in pcts}:
            continue
        if severities is not None and sev not in severities:
            continue
        params = dict(params)
        params.setdefault("fault_type", fault_type)
        params.setdefault("percentage", pct)
        params.setdefault("severity_level", sev)
        rows.append((name, path, params))

    by_fault: Dict[str, List[Tuple[str, Path, dict]]] = {ft: [] for ft in FAULT_TYPES}
    for row in rows:
        fault_type = str(row[2].get("fault_type", ""))
        if fault_type in by_fault:
            by_fault[fault_type].append(row)

    selected: List[Tuple[str, Path, dict]] = []
    max_per_fault = 8 if fast else 36
    for ft in FAULT_TYPES:
        candidates = sorted(by_fault[ft], key=lambda r: (r[0], r[2].get("percentage", 0), r[2].get("severity_level", 0)))
        selected.extend(candidates[:max_per_fault])
    return selected


def _patch_pyarrow_for_pandas() -> None:
    try:
        import pyarrow as pa
        import pyarrow.lib as palib
    except Exception:
        return
    original = getattr(pa, "unregister_extension_type", None)
    if original is None or getattr(original, "_exp9v6_safe", False):
        return

    def safe_unregister(name):
        try:
            return original(name)
        except palib.ArrowKeyError as exc:
            if "No type extension" in str(exc):
                return None
            raise

    safe_unregister._exp9v6_safe = True
    pa.unregister_extension_type = safe_unregister


def _read_parquet(path: Path) -> pd.DataFrame:
    _patch_pyarrow_for_pandas()
    return pd.read_parquet(path, engine="pyarrow")


def _label_array(label_df: pd.DataFrame) -> np.ndarray:
    for col in ("fault_label", "label", "state"):
        if col in label_df.columns:
            return label_df[col].to_numpy()
    raise ValueError(f"No usable label column found: {list(label_df.columns)}")


def _parse_fault_params_from_name(name: str) -> dict:
    m = re.match(r"^(\d{4}-\d{2}-\d{2})_(.+?)_pct(\d+)_sev(\d+)$", name)
    if not m:
        return {"fault_type": "", "percentage": 0.0, "severity_level": 0}
    _, fault_type, pct, sev = m.groups()
    return {
        "fault_type": fault_type,
        "percentage": int(pct) / 100.0,
        "severity_level": int(sev),
    }


def _load_fault_scenario_arrays(name: str, device: str = "BA1") -> Tuple[np.ndarray, np.ndarray]:
    device_dir = get_active_fault_data_dir() / device
    data_path = device_dir / f"{name}_data.parquet"
    label_path = device_dir / f"{name}_labels.parquet"
    if not data_path.exists() or not label_path.exists():
        raise FileNotFoundError(f"Missing active fault scenario parquet files for {name} under {device_dir}")

    feature_cols = get_feature_cols(device)
    data_df = _read_parquet(data_path)
    label_df = _read_parquet(label_path)
    missing = [c for c in feature_cols if c not in data_df.columns]
    if missing:
        raise ValueError(f"Missing active feature columns in {data_path}: {missing}")

    labels = _label_array(label_df)
    n = min(len(data_df), len(labels))
    signal = data_df[feature_cols].iloc[:n].to_numpy(dtype=np.float32)
    labels = (labels[:n] > 0).astype(np.int8)
    return signal, labels


def _window_rms(x: np.ndarray) -> float:
    if len(x) == 0:
        return 0.0
    return float(np.sqrt(np.mean(np.square(x))))


def _load_exp7_dshi_cache(scenario_names: Sequence[str], device: str = "BA1") -> Dict[str, np.ndarray]:
    """Load Exp7 cached DSHI trajectories for the scenarios used by Exp9."""
    cache_dir = THIS_DIR / "outputs" / "exp7_figures"
    cache_tag = os.environ.get("EXP7_DSHI_CACHE_TAG", "sequence_forecasting_v3").strip()
    strict = os.environ.get("EXP7_DSHI_STRICT", "0").strip().lower() in {"1", "true", "yes", "on"}
    npz_path = cache_dir / f"{cache_tag}_dshi_cache_{device}.npz"
    meta_path = cache_dir / f"{cache_tag}_dshi_cache_{device}_meta.csv"
    if not npz_path.exists() or not meta_path.exists():
        if strict:
            raise FileNotFoundError(
                f"Strict Exp7 DSHI mode requires both cache files: {npz_path} and {meta_path}"
            )
        print(f"[Exp9-v6] Exp7 DSHI cache not found, using RMS risk fallback: {npz_path}", flush=True)
        return {}

    wanted = set(scenario_names)
    meta = pd.read_csv(meta_path)
    rows = meta[meta["scenario"].isin(wanted)][["scenario", "array_key"]]
    if rows.empty:
        if strict:
            raise RuntimeError(f"Strict Exp7 DSHI cache {cache_tag!r} has no matching scenarios.")
        print("[Exp9-v6] Exp7 DSHI cache has no matching scenarios, using RMS risk fallback.", flush=True)
        return {}

    out: Dict[str, np.ndarray] = {}
    with np.load(npz_path, allow_pickle=False) as z:
        for row in rows.itertuples(index=False):
            if row.array_key in z.files:
                out[str(row.scenario)] = np.asarray(z[str(row.array_key)], dtype=np.float32)
    missing = sorted(wanted - set(out))
    if strict and missing:
        raise RuntimeError(
            f"Strict Exp7 DSHI cache coverage failed: loaded {len(out)}/{len(wanted)}; "
            f"first missing scenarios: {missing[:5]}"
        )
    print(f"[Exp9-v6] Loaded Exp7 DSHI trajectories: {len(out)}/{len(wanted)} scenarios.", flush=True)
    return out


def _vec_corr(a: np.ndarray, b: np.ndarray) -> float:
    a_c = a - np.mean(a)
    b_c = b - np.mean(b)
    denom = np.sqrt(np.sum(a_c**2) * np.sum(b_c**2))
    if denom <= 1e-12:
        return 0.0
    return float(np.sum(a_c * b_c) / denom)


def _single_window_features(seg: np.ndarray) -> np.ndarray:
    """Exp8-style dynamic time/frequency features for one [T, C] window."""
    x = np.asarray(seg, dtype=np.float32)
    if x.ndim != 2:
        raise ValueError(f"Expected [window, channels] segment, got {x.shape}")
    n_channels = int(x.shape[1])

    per_axis = []
    t = np.arange(len(x), dtype=np.float32)
    t_c = t - np.mean(t)
    var_t = float(np.sum(t_c**2)) + 1e-8
    for j in range(n_channels):
        v = x[:, j]
        mean = float(np.mean(v))
        std = float(np.std(v)) + 1e-8
        centered = v - mean
        z = np.clip(centered / std, -50.0, 50.0)
        slope = float(np.sum(centered * t_c) / var_t)
        per_axis.extend(
            [
                mean,
                std,
                float(np.max(v) - np.min(v)),
                float(np.sqrt(np.mean(v**2))),
                float(np.mean(z**3)),
                float(np.mean(z**4)),
                float(np.mean(np.abs(v))),
                slope,
                float(abs(v[-1] - v[0])),
            ]
        )

    cross = []
    for i in range(n_channels):
        for j in range(i + 1, n_channels):
            cross.append(_vec_corr(x[:, i], x[:, j]))
    cross.append(float(np.mean(np.abs(x))))

    fft_features = []
    for j in range(n_channels):
        mag = np.abs(np.fft.rfft(x[:, j]))
        mag_sum = float(np.sum(mag)) + 1e-12
        norm = mag / mag_sum
        bins = np.arange(len(mag), dtype=np.float32)
        centroid = float(np.sum(norm * bins))
        spread = float(np.sum(norm * (bins - centroid) ** 2))
        low_ratio = float(np.sum(norm[: max(2, len(norm) // 5)]))
        high_ratio = float(np.sum(norm[max(2, len(norm) // 5) :]))
        fft_features.extend(
            [
                float(np.mean(mag)),
                float(np.max(mag)),
                float(np.argmax(mag)),
                centroid,
                spread,
                low_ratio,
                high_ratio,
            ]
        )

    feat = np.asarray(per_axis + cross + fft_features, dtype=np.float32)
    return np.nan_to_num(feat, nan=0.0, posinf=0.0, neginf=0.0)


def _build_window_series(
    signal: np.ndarray,
    label: np.ndarray,
    risk_series: Optional[np.ndarray] = None,
    window_size: int = 120,
    stride: int = 60,
) -> Tuple[np.ndarray, np.ndarray, np.ndarray, np.ndarray]:
    risks, fault_ratios, centers, features = [], [], [], []
    n = min(len(signal), len(label), len(risk_series) if risk_series is not None else len(signal))
    signal = signal[:n]
    label = label[:n]
    if risk_series is not None:
        risk_series = np.nan_to_num(np.asarray(risk_series[:n], dtype=np.float32), nan=0.0, posinf=0.0, neginf=0.0)
    for start in range(0, max(1, n - window_size + 1), stride):
        end = min(n, start + window_size)
        if end - start < max(20, window_size // 3):
            continue
        seg = signal[start:end]
        if risk_series is None:
            risks.append(_window_rms(seg))
        else:
            risks.append(float(max(0.0, np.mean(risk_series[start:end]))))
        fault_ratios.append(float(np.mean(label[start:end] > 0)))
        centers.append((start + end) // 2)
        features.append(_single_window_features(seg))
    return (
        np.asarray(risks, dtype=np.float32),
        np.asarray(fault_ratios, dtype=np.float32),
        np.asarray(centers, dtype=np.int32),
        np.asarray(features, dtype=np.float32),
    )


def _crop_window_arrays(
    risk_raw: np.ndarray,
    fault_ratio: np.ndarray,
    centers: np.ndarray,
    features: np.ndarray,
    max_windows: int = 180,
    pre_windows: int = 35,
    post_windows: int = 35,
) -> Tuple[np.ndarray, np.ndarray, np.ndarray, np.ndarray]:
    fault_idx = np.where(fault_ratio > 0)[0]
    if len(fault_idx) == 0:
        sl = slice(0, min(max_windows, len(risk_raw)))
    else:
        start = max(0, int(fault_idx[0]) - pre_windows)
        end = min(len(risk_raw), int(fault_idx[-1]) + post_windows + 1)
        if end - start > max_windows:
            end = min(len(risk_raw), start + max_windows)
        sl = slice(start, end)
    return risk_raw[sl], fault_ratio[sl], centers[sl], features[sl]


def _risk_threshold(risk_raw: np.ndarray, fault_ratio: np.ndarray) -> float:
    healthy = risk_raw[fault_ratio <= 0.01]
    if len(healthy) < 5:
        healthy = risk_raw[: max(5, len(risk_raw) // 3)]
    base = float(np.percentile(healthy, 90))
    spread = float(np.std(healthy))
    return max(base + 2.5 * spread, base * 1.10, 1e-6)


def load_scenarios(
    fast: bool,
    device: str = "BA1",
    crop_fault_neighborhood: bool = False,
) -> List[Scenario]:
    selected = _select_balanced_params(fast=fast, device=device)
    exp7_dshi = _load_exp7_dshi_cache([name for name, _, _ in selected], device=device)
    scenarios: List[Scenario] = []
    risk_source_counts = {"exp7_dshi": 0, "rms_fallback": 0}

    for name, _, params in tqdm(selected, desc="Loading Exp2 scenarios"):
        parsed = _parse_fault_params_from_name(name)
        fault_type = str(params.get("fault_type", parsed["fault_type"]))
        severity_level = int(params.get("severity_level", parsed["severity_level"]))
        percentage = float(params.get("percentage", parsed["percentage"]))
        physics_severity = float(params.get("physics_severity", severity_level))

        signal, labels = _load_fault_scenario_arrays(name, device=device)
        risk_series = exp7_dshi.get(name)
        risk_source = "exp7_dshi" if risk_series is not None else "rms_fallback"
        risk_source_counts[risk_source] += 1
        risk_raw, fault_ratio, centers, features = _build_window_series(signal, labels, risk_series=risk_series)
        if crop_fault_neighborhood:
            risk_raw, fault_ratio, centers, features = _crop_window_arrays(risk_raw, fault_ratio, centers, features)
        if len(risk_raw) < 20 or np.max(fault_ratio) <= 0:
            continue
        threshold = _risk_threshold(risk_raw, fault_ratio)
        scenarios.append(
            Scenario(
                name=name,
                date=_parse_date_from_name(name),
                fault_type=fault_type,
                severity_level=severity_level,
                percentage=percentage,
                physics_severity=physics_severity,
                risk_raw=risk_raw.astype(np.float32),
                fault_ratio=fault_ratio.astype(np.float32),
                window_features=features.astype(np.float32),
                risk_threshold=float(threshold),
                risk_source=risk_source,
            )
        )
    print(f"[Exp9-v6] Risk source counts: {risk_source_counts}", flush=True)
    return scenarios


def split_scenarios(scenarios: List[Scenario]) -> Tuple[List[Scenario], List[Scenario]]:
    train, test = [], []
    for ft in FAULT_TYPES:
        group = sorted([s for s in scenarios if s.fault_type == ft], key=lambda s: (s.date, s.percentage, s.severity_level))
        if not group:
            continue
        n_train = max(1, int(len(group) * 0.70))
        if n_train >= len(group) and len(group) > 1:
            n_train = len(group) - 1
        train.extend(group[:n_train])
        test.extend(group[n_train:])
    return train, test


class Exp8WindowDiagnostic:
    """Train/test separated Exp8-style window fault classifier."""

    def __init__(self, random_state: int = 42):
        self.scaler = StandardScaler()
        self.model = ExtraTreesClassifier(
            n_estimators=320,
            max_depth=None,
            min_samples_leaf=2,
            class_weight="balanced",
            random_state=random_state,
            n_jobs=-1,
        )
        self.classes_: Optional[np.ndarray] = None
        self.report: Dict[str, object] = {}

    def fit(self, scenarios: Sequence[Scenario]) -> "Exp8WindowDiagnostic":
        xs, ys = [], []
        for sc in scenarios:
            mask = sc.fault_ratio >= 0.25
            if not np.any(mask):
                continue
            xs.append(sc.window_features[mask])
            ys.extend([FAULT_TO_ID[sc.fault_type]] * int(np.sum(mask)))
        if not xs:
            raise RuntimeError("No faulty training windows for Exp8 diagnostic model.")
        x = np.vstack(xs)
        y = np.asarray(ys, dtype=np.int64)
        x_scaled = self.scaler.fit_transform(x)
        self.model.fit(x_scaled, y)
        self.classes_ = np.asarray(self.model.classes_, dtype=np.int64)
        pred = self.model.predict(x_scaled)
        self.report["train_fault_window_accuracy"] = float(accuracy_score(y, pred))
        self.report["train_fault_windows"] = int(len(y))
        self.report["train_class_counts"] = {FAULT_TYPES[i]: int(np.sum(y == i)) for i in range(len(FAULT_TYPES))}
        return self

    def predict_proba(self, features: np.ndarray) -> np.ndarray:
        if self.classes_ is None:
            raise RuntimeError("Diagnostic model has not been fitted.")
        raw = self.model.predict_proba(self.scaler.transform(features))
        out = np.zeros((len(features), len(FAULT_TYPES)), dtype=np.float32)
        for j, cls in enumerate(self.classes_):
            out[:, int(cls)] = raw[:, j]
        row_sum = out.sum(axis=1, keepdims=True)
        out = np.divide(out, np.clip(row_sum, 1e-12, None))
        return out.astype(np.float32)

    def evaluate_fault_windows(self, scenarios: Sequence[Scenario]) -> dict:
        xs, ys = [], []
        for sc in scenarios:
            mask = sc.fault_ratio >= 0.25
            if not np.any(mask):
                continue
            xs.append(sc.window_features[mask])
            ys.extend([FAULT_TO_ID[sc.fault_type]] * int(np.sum(mask)))
        if not xs:
            return {"test_fault_window_accuracy": 0.0, "test_fault_windows": 0}
        x = np.vstack(xs)
        y = np.asarray(ys, dtype=np.int64)
        pred = np.argmax(self.predict_proba(x), axis=1)
        cm = confusion_matrix(y, pred, labels=list(range(len(FAULT_TYPES))))
        return {
            "test_fault_window_accuracy": float(accuracy_score(y, pred)),
            "test_fault_windows": int(len(y)),
            "test_confusion": cm.tolist(),
        }


def attach_exp8_probabilities(
    train_scenarios: Sequence[Scenario],
    test_scenarios: Sequence[Scenario],
    out_dir: Path,
) -> Tuple[List[Scenario], List[Scenario], Exp8WindowDiagnostic]:
    diagnostic = Exp8WindowDiagnostic(random_state=42).fit(train_scenarios)
    diagnostic.report.update(diagnostic.evaluate_fault_windows(test_scenarios))

    def _attach(sc: Scenario) -> Scenario:
        return replace(sc, diagnostic_proba=diagnostic.predict_proba(sc.window_features))

    train_out = [_attach(sc) for sc in train_scenarios]
    test_out = [_attach(sc) for sc in test_scenarios]

    rows = []
    for split, group in [("train", train_out), ("test", test_out)]:
        for sc in group:
            for i, probs in enumerate(sc.diagnostic_proba):
                rows.append(
                    {
                        "split": split,
                        "scenario": sc.name,
                        "fault_type": sc.fault_type,
                        "window": i,
                        "risk_raw": float(sc.risk_raw[i]),
                        "fault_ratio": float(sc.fault_ratio[i]),
                        **{f"p_{ft}": float(probs[j]) for j, ft in enumerate(FAULT_TYPES)},
                    }
                )
    pd.DataFrame(rows).to_csv(out_dir / "exp9_v6_exp8_window_probabilities.csv", index=False, encoding="utf-8-sig")
    with open(out_dir / "exp9_v6_exp8_diagnostic_report.json", "w", encoding="utf-8") as f:
        json.dump(diagnostic.report, f, indent=2, ensure_ascii=False)
    return train_out, test_out, diagnostic


class MaintenanceEnv:
    """Window-level maintenance decision environment with hidden labels."""

    def __init__(self, scenario: Scenario, seed: int = 42, cost_cfg: Optional[CostConfig] = None):
        if scenario.diagnostic_proba is None:
            raise ValueError("Scenario must contain Exp8 diagnostic probabilities.")
        self.scenario = scenario
        self.rng = np.random.default_rng(seed)
        self.cost_cfg = cost_cfg or CostConfig()
        self.base_risk = scenario.risk_raw / max(scenario.risk_threshold, 1e-6)
        self.fault_ratio = scenario.fault_ratio.astype(np.float32)
        self.diagnostic_proba = scenario.diagnostic_proba.astype(np.float32)
        self.n = len(self.base_risk)
        self.reset()

    def reset(self) -> np.ndarray:
        self.t = 0
        self.suppression = 0.0
        self.suppression_left = 0
        self.time_since_action = 30.0
        self.last_action = 0
        self.action_cooldown_left = 0
        self.inspection_left = 0
        self.unmitigated_streak = 0
        self.history: List[dict] = []
        self.risk_history: List[float] = []
        return self._state()

    def _effective_risk(self, idx: Optional[int] = None) -> float:
        if idx is None:
            idx = self.t
        raw = float(self.base_risk[min(idx, self.n - 1)])
        return max(0.0, raw * (1.0 - self.suppression))

    def _forecast_risk(self, hist: np.ndarray) -> Tuple[float, float, float, float]:
        trend = float(hist[-1] - hist[0]) / max(len(hist) - 1, 1)
        volatility = float(np.std(hist))
        max_recent = float(np.max(hist))
        forecast = float(np.clip(hist[-1] + 7.0 * trend + 0.35 * volatility, 0.0, 3.0))
        return forecast, trend, volatility, max_recent

    def _dmt_index(self) -> float:
        # DMT-inspired state factor from the previous paper: criticality,
        # conservative preference, and age/degradation state.
        type_criticality = {
            "crack": 0.92,
            "mechanical_looseness": 0.82,
            "thermal": 0.72,
            "imbalance": 0.62,
        }[self.scenario.fault_type]
        proactive_preference = 0.74
        age_state = 1.0 / (1.0 + np.exp(-5.0 * ((self.t + 1) / max(self.n, 1) - 0.5)))
        return float((type_criticality * proactive_preference * age_state) ** (1.0 / 3.0))

    def _diagnostic_state(self, risk: float) -> Tuple[np.ndarray, float, float]:
        probs = self.diagnostic_proba[min(self.t, self.n - 1)].copy()
        if self.inspection_left > 0:
            top = int(np.argmax(probs))
            probs *= 0.72
            probs[top] += 0.28
            probs /= max(float(np.sum(probs)), 1e-12)
        anomaly_gate = float(np.clip((risk - 0.35) / 0.85, 0.05, 1.0))
        conf = float(np.max(probs) * anomaly_gate)
        entropy = float(-np.sum(probs * np.log(np.clip(probs, 1e-12, 1.0))) / np.log(len(FAULT_TYPES)))
        return probs.astype(np.float32), conf, entropy

    def _state(self) -> np.ndarray:
        risk = self._effective_risk()
        hist = (self.risk_history + [risk])[-8:]
        if len(hist) < 8:
            hist = [hist[0] if hist else risk] * (8 - len(hist)) + hist
        arr = np.asarray(hist, dtype=np.float32)
        forecast, trend, volatility, max_recent = self._forecast_risk(arr)
        if trend > 1e-5 and risk < 1.0:
            time_to = float(np.clip((1.0 - risk) / (trend * 20.0), 0.0, 1.0))
        else:
            time_to = 1.0 if risk < 1.0 else 0.0
        diag, diag_conf, diag_entropy = self._diagnostic_state(risk)
        last_action_oh = np.zeros(N_ACTIONS, dtype=np.float32)
        last_action_oh[int(self.last_action)] = 1.0
        state = np.concatenate(
            [
                np.clip(arr, 0.0, 3.0) / 3.0,
                np.asarray(
                    [
                        np.clip(risk, 0.0, 3.0) / 3.0,
                        np.clip(trend, -0.5, 0.5),
                        np.clip(volatility, 0.0, 1.0),
                        np.clip(max_recent, 0.0, 3.0) / 3.0,
                        forecast / 3.0,
                        time_to,
                        min(self.time_since_action / 30.0, 1.0),
                        np.clip(self.suppression, 0.0, 1.0),
                    ],
                    dtype=np.float32,
                ),
                diag,
                np.asarray([diag_conf, diag_entropy, self._dmt_index()], dtype=np.float32),
                last_action_oh,
            ]
        )
        return state.astype(np.float32)

    @property
    def state_dim(self) -> int:
        return len(self._state())

    def _failure_base_cost(self) -> float:
        base = {
            "crack": 56.0,
            "mechanical_looseness": 48.0,
            "thermal": 38.0,
            "imbalance": 32.0,
        }[self.scenario.fault_type]
        sev_factor = 0.70 + 0.55 * float(np.clip(self.scenario.physics_severity, 0.0, 1.2))
        return base * sev_factor

    def _action_costs(self, action: int) -> Tuple[float, float]:
        c = self.cost_cfg
        if action == 1:
            return c.inspect_cost, c.inspect_downtime * c.downtime_unit_cost
        if action == 2:
            return c.preventive_cost, c.preventive_downtime * c.downtime_unit_cost
        if action == 3:
            return c.immediate_cost, c.immediate_downtime * c.downtime_unit_cost
        return 0.0, 0.0

    def _zone_flags(self, risk: float, forecast: float, fault_ratio: float, diag_conf: float) -> dict:
        failure_zone = bool(risk >= 1.0 or fault_ratio >= 0.25)
        warning_zone = bool(0.68 <= risk < 1.0 or 0.80 <= forecast < 1.15 or 0.05 <= fault_ratio < 0.25 or diag_conf >= 0.50)
        critical_zone = bool(risk >= 1.45 or fault_ratio >= 0.65 or forecast >= 1.45)
        low_zone = bool(not failure_zone and not warning_zone)
        return {
            "failure_zone": failure_zone,
            "warning_zone": warning_zone,
            "critical_zone": critical_zone,
            "low_zone": low_zone,
        }

    def _reward(self, action: int, risk: float, forecast: float, fault_ratio: float, diag_conf: float) -> Tuple[float, dict]:
        c = self.cost_cfg
        flags = self._zone_flags(risk, forecast, fault_ratio, diag_conf)
        maintenance_cost, downtime_cost = self._action_costs(action)
        risk_exposure_cost = c.risk_exposure_weight * max(0.0, risk - 0.55) ** 2
        failure_cost = 0.0
        unnecessary_cost = 0.0
        repeated_cost = 0.0

        if action == 0:
            operating_benefit = c.operation_benefit
            if flags["failure_zone"]:
                failure_cost = self._failure_base_cost() * (1.0 + 0.18 * self.unmitigated_streak)
                self.unmitigated_streak += 1
            else:
                self.unmitigated_streak = 0
        else:
            operating_benefit = 0.10 * c.operation_benefit
            self.unmitigated_streak = 0
            if flags["low_zone"]:
                unnecessary_cost = {
                    1: c.low_risk_inspect_penalty,
                    2: c.low_risk_preventive_penalty,
                    3: c.low_risk_immediate_penalty,
                }[action]
            if flags["failure_zone"]:
                if action == 1:
                    failure_cost = self._failure_base_cost() * 0.45
                elif action == 2 and flags["critical_zone"]:
                    failure_cost = self._failure_base_cost() * 0.18
                elif action == 2:
                    failure_cost = self._failure_base_cost() * 0.05
                else:
                    failure_cost = 0.0
            if action > 0 and self.time_since_action < 3.0:
                repeated_cost = c.repeated_maintenance_penalty

        total_cost = maintenance_cost + downtime_cost + risk_exposure_cost + failure_cost + unnecessary_cost + repeated_cost
        reward = operating_benefit - total_cost
        info = {
            "risk": float(risk),
            "forecast_risk": float(forecast),
            "fault_ratio": float(fault_ratio),
            "diag_conf": float(diag_conf),
            "maintenance_cost": float(maintenance_cost),
            "downtime_cost": float(downtime_cost),
            "risk_exposure_cost": float(risk_exposure_cost),
            "failure_cost": float(failure_cost),
            "unnecessary_cost": float(unnecessary_cost),
            "repeated_cost": float(repeated_cost),
            "unmitigated": bool(action == 0 and flags["failure_zone"]),
            **flags,
        }
        return float(reward), info

    def step(self, action: int) -> Tuple[np.ndarray, float, bool, dict]:
        requested_action = int(np.clip(action, 0, N_ACTIONS - 1))
        action = 0 if requested_action > 0 and self.action_cooldown_left > 0 else requested_action
        state = self._state()
        risk = float(state[IDX_CURRENT_RISK] * 3.0)
        forecast = float(state[IDX_FORECAST_RISK] * 3.0)
        diag_conf = float(state[IDX_DIAG_CONF])
        fault_ratio = float(self.fault_ratio[min(self.t, self.n - 1)])
        reward, info = self._reward(action, risk, forecast, fault_ratio, diag_conf)
        info["requested_action"] = requested_action
        info["action"] = action

        if action == 1:
            self.inspection_left = max(self.inspection_left, 3)
            self.action_cooldown_left = max(self.action_cooldown_left, 2)
            self.time_since_action = 0.0
        elif action == 2:
            self.suppression = max(self.suppression, 0.55)
            self.suppression_left = max(self.suppression_left, 8)
            self.action_cooldown_left = max(self.action_cooldown_left, 8)
            self.time_since_action = 0.0
        elif action == 3:
            self.suppression = max(self.suppression, 0.90)
            self.suppression_left = max(self.suppression_left, 14)
            self.action_cooldown_left = max(self.action_cooldown_left, 14)
            self.time_since_action = 0.0
        else:
            self.time_since_action += 1.0

        self.history.append(
            {
                "step": self.t,
                "requested_action": requested_action,
                "action": action,
                "action_name": ACTION_NAMES[action],
                "reward": float(reward),
                **info,
            }
        )
        self.risk_history.append(risk)
        self.last_action = action
        self.t += 1

        if self.inspection_left > 0:
            self.inspection_left -= 1
        if self.action_cooldown_left > 0:
            self.action_cooldown_left -= 1
        if self.suppression_left > 0:
            self.suppression_left -= 1
            if self.suppression_left == 0:
                self.suppression *= 0.25
        else:
            self.suppression *= 0.90
        done = self.t >= self.n
        return self._state(), float(reward), done, info

    def run_policy(self, policy_fn: Callable[[np.ndarray], int]) -> Tuple[List[float], List[int], List[dict]]:
        state = self.reset()
        rewards, actions = [], []
        done = False
        while not done:
            requested_action = int(policy_fn(state))
            state, reward, done, info = self.step(requested_action)
            rewards.append(reward)
            actions.append(int(info.get("action", requested_action)))
        return rewards, actions, list(self.history)


def make_envs(scenarios: Sequence[Scenario], seed: int) -> List[MaintenanceEnv]:
    return [MaintenanceEnv(sc, seed=seed + i) for i, sc in enumerate(scenarios)]


def _identity_encoder(state: np.ndarray) -> np.ndarray:
    return np.asarray(state, dtype=np.float32)


def _plain_dqn_encoder(state: np.ndarray) -> np.ndarray:
    s = np.asarray(state, dtype=np.float32)
    return np.concatenate(
        [
            s[IDX_CURRENT_RISK : IDX_SUPPRESSION + 1],
            s[IDX_DIAG_START:IDX_DIAG_END],
            s[[IDX_DIAG_CONF, IDX_DIAG_ENTROPY]],
            s[IDX_LAST_ACTION_START : IDX_LAST_ACTION_START + N_ACTIONS],
        ]
    ).astype(np.float32)


def _sequence_dqn_encoder(state: np.ndarray) -> np.ndarray:
    s = np.asarray(state, dtype=np.float32)
    return np.concatenate([s[:IDX_DIAG_END], s[[IDX_DIAG_CONF, IDX_DIAG_ENTROPY]], s[IDX_LAST_ACTION_START:]]).astype(np.float32)


def _attention_dqn_encoder(state: np.ndarray) -> np.ndarray:
    s = np.asarray(state, dtype=np.float32)
    hist = s[:8] * 3.0
    # Fixed temporal-attention port of the previous paper: emphasize recent and
    # rapidly increasing risk windows while staying NumPy-only.
    recency = np.linspace(-0.35, 0.35, len(hist), dtype=np.float32)
    logits = 1.2 * hist + recency
    logits = logits - float(np.max(logits))
    weights = np.exp(logits)
    weights = weights / max(float(np.sum(weights)), 1e-12)
    context = float(np.sum(weights * hist))
    attn_slope = float(np.sum(weights * (hist - np.mean(hist))))
    attn_peak = float(np.max(weights * hist))
    return np.concatenate(
        [
            np.asarray([context / 3.0, attn_slope, attn_peak / 3.0], dtype=np.float32),
            weights.astype(np.float32),
            s[IDX_CURRENT_RISK : IDX_LAST_ACTION_START + N_ACTIONS],
        ]
    ).astype(np.float32)


def _torch_sequence_encoder(state: np.ndarray) -> np.ndarray:
    """Build an 8-step sequence for LSTM-style decision models."""
    s = np.asarray(state, dtype=np.float32)
    hist = s[:8]
    delta = np.concatenate([[0.0], np.diff(hist)]).astype(np.float32)
    global_part = np.concatenate(
        [
            s[IDX_CURRENT_RISK : IDX_SUPPRESSION + 1],
            s[IDX_DIAG_START:IDX_DIAG_END],
            s[[IDX_DIAG_CONF, IDX_DIAG_ENTROPY, IDX_DMT]],
            s[IDX_LAST_ACTION_START : IDX_LAST_ACTION_START + N_ACTIONS],
        ]
    ).astype(np.float32)
    seq = []
    for i in range(8):
        pos = np.asarray([i / 7.0], dtype=np.float32)
        seq.append(np.concatenate([[hist[i], delta[i]], pos, global_part]))
    return np.asarray(seq, dtype=np.float32)


class TemporalAttention(nn.Module):
    def __init__(self, hidden_dim: int):
        super().__init__()
        self.w = nn.Linear(hidden_dim, hidden_dim)
        self.v = nn.Linear(hidden_dim, 1)

    def forward(self, x: torch.Tensor) -> Tuple[torch.Tensor, torch.Tensor]:
        score = self.v(torch.tanh(self.w(x))).squeeze(-1)
        attn = torch.softmax(score, dim=1)
        context = torch.sum(x * attn.unsqueeze(-1), dim=1)
        return context, attn


class TorchQNetwork(nn.Module):
    def __init__(
        self,
        input_shape: Tuple[int, ...],
        n_actions: int,
        mode: str,
        hidden_dim: int = 64,
        n_quantiles: Optional[int] = None,
    ):
        super().__init__()
        self.mode = mode
        self.n_actions = n_actions
        self.n_quantiles = n_quantiles
        out_dim = n_actions if n_quantiles is None else n_actions * n_quantiles

        if mode == "plain":
            input_dim = int(input_shape[0])
            self.net = nn.Sequential(
                nn.Linear(input_dim, hidden_dim),
                nn.ReLU(),
                nn.LayerNorm(hidden_dim),
                nn.Linear(hidden_dim, hidden_dim),
                nn.ReLU(),
                nn.Linear(hidden_dim, out_dim),
            )
        elif mode == "dueling_plain":
            if n_quantiles is not None:
                raise ValueError("Dueling mode is only used for scalar Q networks in Exp9-v6.")
            input_dim = int(input_shape[0])
            self.feature = nn.Sequential(
                nn.Linear(input_dim, hidden_dim),
                nn.ReLU(),
                nn.LayerNorm(hidden_dim),
                nn.Linear(hidden_dim, hidden_dim),
                nn.ReLU(),
            )
            self.value_head = nn.Linear(hidden_dim, 1)
            self.advantage_head = nn.Linear(hidden_dim, n_actions)
        elif mode == "lstm":
            input_dim = int(input_shape[-1])
            self.lstm = nn.LSTM(input_dim, hidden_dim, num_layers=1, batch_first=True)
            self.head = nn.Sequential(nn.LayerNorm(hidden_dim), nn.Linear(hidden_dim, out_dim))
        elif mode == "hilstm_attn":
            input_dim = int(input_shape[-1])
            self.low_lstm = nn.LSTM(input_dim, 64, num_layers=1, batch_first=True)
            self.high_lstm = nn.LSTM(64, hidden_dim, num_layers=1, batch_first=True)
            self.attention = TemporalAttention(hidden_dim)
            self.head = nn.Sequential(nn.LayerNorm(hidden_dim), nn.Linear(hidden_dim, out_dim))
        else:
            raise ValueError(f"Unknown TorchQNetwork mode: {mode}")

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        if self.mode == "plain":
            out = self.net(x)
        elif self.mode == "dueling_plain":
            z = self.feature(x)
            value = self.value_head(z)
            advantage = self.advantage_head(z)
            out = value + advantage - advantage.mean(dim=1, keepdim=True)
        elif self.mode == "lstm":
            y, _ = self.lstm(x)
            out = self.head(y[:, -1, :])
        else:
            low, _ = self.low_lstm(x)
            high, _ = self.high_lstm(low)
            context, _ = self.attention(high)
            out = self.head(context)
        if self.n_quantiles is not None:
            out = out.view(out.shape[0], self.n_actions, self.n_quantiles)
        return out


class TorchReplayBase:
    def __init__(
        self,
        raw_state_dim: int,
        encoder: Callable[[np.ndarray], np.ndarray],
        mode: str,
        n_actions: int = 4,
        gamma: float = 0.96,
        lr: float = 5e-4,
        epsilon_decay: float = 0.993,
        batch_size: int = 96,
        replay_size: int = 80000,
        target_update: int = 80,
        seed: int = 42,
    ):
        self.n_actions = n_actions
        self.encoder = encoder
        self.feature_shape = tuple(self.encoder(np.zeros(raw_state_dim, dtype=np.float32)).shape)
        self.mode = mode
        self.gamma = gamma
        self.epsilon = 1.0
        self.epsilon_min = 0.05
        self.epsilon_decay = epsilon_decay
        self.batch_size = batch_size
        self.replay_size = replay_size
        self.target_update = target_update
        self.buffer: List[Tuple[np.ndarray, int, float, np.ndarray, bool]] = []
        self.training_step = 0
        self.rng = np.random.default_rng(seed)
        torch.manual_seed(seed)
        self.device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
        self.lr = lr

    def encode(self, state: np.ndarray) -> np.ndarray:
        return self.encoder(state).astype(np.float32)

    def store(self, s: np.ndarray, a: int, r: float, sn: np.ndarray, done: bool):
        self.buffer.append((self.encode(s), int(a), float(r), self.encode(sn), bool(done)))
        if len(self.buffer) > self.replay_size:
            del self.buffer[: len(self.buffer) - self.replay_size]

    def _sample_tensors(self):
        batch = random.sample(self.buffer, min(self.batch_size, len(self.buffer)))
        s, a, r, sn, done = zip(*batch)
        return (
            torch.as_tensor(np.asarray(s, dtype=np.float32), device=self.device),
            torch.as_tensor(np.asarray(a, dtype=np.int64), device=self.device),
            torch.as_tensor(np.asarray(r, dtype=np.float32), device=self.device),
            torch.as_tensor(np.asarray(sn, dtype=np.float32), device=self.device),
            torch.as_tensor(np.asarray(done, dtype=np.float32), device=self.device),
        )

    def _state_dict_cpu(self, net: nn.Module) -> dict:
        return {k: v.detach().cpu().clone() for k, v in net.state_dict().items()}

    def _load_net_state(self, net: nn.Module, state: dict):
        net.load_state_dict({k: v.to(self.device) if torch.is_tensor(v) else v for k, v in state.items()})


class TorchDQNAgent(TorchReplayBase):
    def __init__(
        self,
        raw_state_dim: int,
        encoder: Callable[[np.ndarray], np.ndarray],
        mode: str,
        double_dqn: bool = False,
        **kwargs,
    ):
        super().__init__(raw_state_dim=raw_state_dim, encoder=encoder, mode=mode, **kwargs)
        self.double_dqn = bool(double_dqn)
        self.q_eval = TorchQNetwork(self.feature_shape, self.n_actions, mode=mode).to(self.device)
        self.q_target = TorchQNetwork(self.feature_shape, self.n_actions, mode=mode).to(self.device)
        self.q_target.load_state_dict(self.q_eval.state_dict())
        self.optimizer = optim.AdamW(self.q_eval.parameters(), lr=self.lr, weight_decay=1e-4)
        self.loss_fn = nn.SmoothL1Loss()

    def select_action(self, state: np.ndarray, training: bool = True) -> int:
        if training and random.random() < self.epsilon:
            return random.randrange(self.n_actions)
        x = torch.as_tensor(self.encode(state)[None, ...], dtype=torch.float32, device=self.device)
        with torch.no_grad():
            q = self.q_eval(x)[0]
        return int(torch.argmax(q).item())

    def update(self) -> Optional[float]:
        if len(self.buffer) < self.batch_size:
            return None
        s, a, r, sn, done = self._sample_tensors()
        q_pred = self.q_eval(s).gather(1, a[:, None]).squeeze(1)
        with torch.no_grad():
            if self.double_dqn:
                next_a = torch.argmax(self.q_eval(sn), dim=1)
                q_next = self.q_target(sn).gather(1, next_a[:, None]).squeeze(1)
            else:
                q_next = self.q_target(sn).max(dim=1).values
            target = r + self.gamma * (1.0 - done) * q_next
        loss = self.loss_fn(q_pred, target)
        self.optimizer.zero_grad(set_to_none=True)
        loss.backward()
        nn.utils.clip_grad_norm_(self.q_eval.parameters(), 3.0)
        self.optimizer.step()
        self.epsilon = max(self.epsilon_min, self.epsilon * self.epsilon_decay)
        self.training_step += 1
        if self.training_step % self.target_update == 0:
            self.q_target.load_state_dict(self.q_eval.state_dict())
        return float(loss.detach().cpu().item())

    def get_state(self) -> dict:
        return {
            "q_eval": self._state_dict_cpu(self.q_eval),
            "q_target": self._state_dict_cpu(self.q_target),
            "epsilon": float(self.epsilon),
        }

    def load_state(self, state: dict):
        self._load_net_state(self.q_eval, state["q_eval"])
        self._load_net_state(self.q_target, state.get("q_target", state["q_eval"]))
        self.epsilon = float(state.get("epsilon", self.epsilon))


