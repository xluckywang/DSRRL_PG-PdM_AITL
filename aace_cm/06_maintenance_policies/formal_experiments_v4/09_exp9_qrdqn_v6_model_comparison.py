def fixed_policy(threshold: float, action: int = 2) -> Callable[[np.ndarray], int]:
    def _policy(state: np.ndarray) -> int:
        risk = float(state[IDX_CURRENT_RISK] * 3.0)
        return action if risk >= threshold else 0

    return _policy


def periodic_policy(period: float = 24.0) -> Callable[[np.ndarray], int]:
    def _policy(state: np.ndarray) -> int:
        time_since = float(state[IDX_TIME_SINCE_ACTION] * 30.0)
        return 2 if time_since >= period else 0

    return _policy


def greedy_risk_policy(state: np.ndarray) -> int:
    risk = float(state[IDX_CURRENT_RISK] * 3.0)
    forecast = float(state[IDX_FORECAST_RISK] * 3.0)
    diag_conf = float(state[IDX_DIAG_CONF])
    entropy = float(state[IDX_DIAG_ENTROPY])
    if risk >= 1.35 or forecast >= 1.45:
        return 3
    if risk >= 0.82 or forecast >= 1.0:
        return 2
    if risk >= 0.58 and diag_conf >= 0.42 and entropy > 0.30:
        return 1
    return 0


def dmt_heuristic_policy(state: np.ndarray) -> int:
    risk = float(state[IDX_CURRENT_RISK] * 3.0)
    forecast = float(state[IDX_FORECAST_RISK] * 3.0)
    dmt = float(state[IDX_DMT])
    diag_conf = float(state[IDX_DIAG_CONF])
    # Larger DMT makes the policy more proactive.
    preventive_threshold = 0.95 - 0.25 * dmt
    inspect_threshold = 0.62 - 0.12 * dmt
    immediate_threshold = 1.42 - 0.18 * dmt
    if max(risk, forecast) >= immediate_threshold:
        return 3
    if max(risk, forecast) >= preventive_threshold:
        return 2
    if max(risk, forecast) >= inspect_threshold and diag_conf >= 0.35:
        return 1
    return 0


def _scorer_dqn_encoder(state: np.ndarray) -> np.ndarray:
    s = np.asarray(state, dtype=np.float32)
    hist = s[:8]
    risk_block = s[IDX_CURRENT_RISK : IDX_SUPPRESSION + 1]
    diag = s[IDX_DIAG_START:IDX_DIAG_END]
    diag_meta = s[[IDX_DIAG_CONF, IDX_DIAG_ENTROPY, IDX_DMT]]
    last_action = s[IDX_LAST_ACTION_START : IDX_LAST_ACTION_START + N_ACTIONS]
    recent_weights = np.linspace(0.45, 1.25, len(hist), dtype=np.float32)
    weighted_hist = hist * recent_weights
    interaction = np.asarray(
        [
            s[IDX_CURRENT_RISK] * s[IDX_DIAG_CONF],
            s[IDX_FORECAST_RISK] * s[IDX_DMT],
            s[IDX_VOLATILITY] * (1.0 - s[IDX_DIAG_ENTROPY]),
            np.max(hist) - np.mean(hist),
        ],
        dtype=np.float32,
    )
    return np.concatenate([weighted_hist, risk_block, diag, diag_meta, last_action, interaction]).astype(np.float32)


